"""Gunmen Wars: the NamCam screen's two captions as 8-bit alpha masks (src/gw_namcam_text.h).
On the cabinet the GMEN board draws them (its own video); the main board's program never does. Rendered from Windows' Yu Gothic Bold,
laid out after the real machine (the user's photos): "顔" large + "を撮影します" under it, then "顔の位置を合わせてください" under the
camera picture. Run:  python tools/make_namcam_text.py  (needs Pillow and C:/Windows/Fonts/YuGothB.ttc)"""
import os
from PIL import Image, ImageDraw, ImageFont

FONT = 'C:/Windows/Fonts/YuGothB.ttc'
OUT = os.path.join(os.path.dirname(__file__), '..', 'src', 'gw_namcam_text.h')

def mask(text, size, pad=2):
    f = ImageFont.truetype(FONT, size)
    l, t, r, b = f.getbbox(text)
    im = Image.new('L', (r - l + 2 * pad, b - t + 2 * pad), 0)
    ImageDraw.Draw(im).text((pad - l, pad - t), text, font=f, fill=255)
    return im

items = [('gw_txt_face', mask('顔', 64)), ('gw_txt_shoot', mask('を撮影します', 34)), ('gw_txt_align', mask('顔の位置を合わせてください', 22))]
# THE PAC-MAN of the board's power-on test (its text layer, frames 300 / 302 / 314 of a headless boot): wide, half, closed -- 13 x 13,
# facing right; the boot NOTICE shows two in white either side of its countdown (the user's choice), the right one mirrored
PAC = ["""....#####....
..########...
.#########...
.########....
######.......
####.........
##...........
####.........
######.......
.########....
.#########...
..########...
....#####....""", """....####.....
..######.....
.######......
.#####.......
####.........
##...........
#............
##...........
####.........
.#####.......
.######......
..######.....
....####.....""", """....#####....
..#########..
.###########.
.###########.
#############
#############
#############
#############
#############
.###########.
.###########.
..#########..
....#####...."""]
for k, t in enumerate(PAC):
    rows = t.splitlines(); im = Image.new('L', (13, 13), 0)
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == '#': im.putpixel((x, y), 255)
    items.append(('gw_pac%d' % k, im)); items.append(('gw_pacm%d' % k, im.transpose(Image.FLIP_LEFT_RIGHT)))
with open(OUT, 'w', encoding='utf-8', newline='\n') as o:
    o.write('/* GENERATED by tools/make_namcam_text.py -- the NamCam captions (8-bit alpha, row-major) */\n')
    for name, im in items:
        w, h = im.size
        data = im.tobytes()
        o.write('static const int %s_w = %d, %s_h = %d;\nstatic const unsigned char %s[%d] = {\n' % (name, w, name, h, name, w * h))
        for i in range(0, len(data), 32):
            o.write(','.join(str(b) for b in data[i:i + 32]) + ',\n')
        o.write('};\n')
print('wrote', OUT, [(n, im.size) for n, im in items])
